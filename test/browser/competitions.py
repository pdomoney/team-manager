# Competitions: one competition, several teams entered through their seasons, fixtures linked to
# entries, friendlies and unlinked matches, tournament days, completing, Home, rules, reports, players.
import sys, json; from harness import *
from playwright.sync_api import sync_playwright
build(); srv, url = serve()
c = Check()
act = "([a, ds]) => { const b = document.createElement('button'); b.dataset.act = a; Object.assign(b.dataset, ds || {}); document.body.appendChild(b); b.click(); b.remove(); }"
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx, pg, errs = page(b, url + '#home', width=390, height=844)
    W = lambda js: pg.evaluate(f'(() => {{ const W = window.__team.ws, D = window.__team.data, M = window.__team.M, S = window.__team.state; return {js}; }})()')
    pg.wait_for_selector('text=Load a sample squad'); pg.click('[data-act=sample]'); pg.wait_for_timeout(300)
    cup = W('D.team.eventCompId')
    c.ok(W('W.competitions.length') == 1 and W(f"M.compMatches(W, '{cup}').length") >= 3, 'the tournament is a competition with its matches')
    # a second team in another club
    pg.goto(url + '#teams'); pg.wait_for_timeout(100)
    pg.click('[data-act=team-new]'); pg.fill('#sheet input[name=name]', 'Titans Women'); pg.select_option('#sheet select[name=category]', 'women')
    pg.click('#sheet form[data-form=team-new] button[type=submit]'); pg.wait_for_timeout(200)
    women = W('D.id'); wseason = W('M.activeSeason(D).id')
    pg.evaluate(act, ['team-pick', {'id': 'team1'}]); pg.wait_for_timeout(100)
    # create Winter League 2027 from More › Competitions
    pg.goto(url + '#more'); pg.wait_for_timeout(100); pg.click('[data-act=tab][data-tab=comps]'); pg.wait_for_timeout(150)
    pg.click('[data-act=comp-new]'); pg.wait_for_selector('#sheet form[data-form=comp]')
    pg.fill('#sheet input[name=name]', 'Winter League 2027'); pg.select_option('#sheet select[name=format]', 'league')
    pg.fill('#sheet input[name=start]', W('M.addDays(M.isoDay(new Date()), -10)')); pg.fill('#sheet input[name=end]', W('M.addDays(M.isoDay(new Date()), 120)'))
    pg.fill('#sheet textarea[name=bylaws]', 'Games are 2 × 20 minutes.\nNo kicking in the last 2 minutes.')
    pg.click('#sheet form[data-form=comp] button[type=submit]'); pg.wait_for_timeout(200)
    wl = W("W.competitions.find(c => c.name === 'Winter League 2027').id")
    c.ok(bool(wl) and 'Winter League 2027' in pg.inner_text('#view'), 'competition created and opened')
    # enter both teams through their seasons
    pg.click('[data-act=comp-entry-new]'); pg.wait_for_selector('#sheet form[data-form=comp-entry]')
    pg.fill('#sheet input[name=division]', 'Mixed Open'); pg.click('#sheet form[data-form=comp-entry] button[type=submit]'); pg.wait_for_timeout(150)
    pg.click('[data-act=comp-entry-new]'); pg.wait_for_selector('#sheet form[data-form=comp-entry]')
    pg.select_option('#sheet select[name=ts]', f'{women}|{wseason}'); pg.fill('#sheet input[name=division]', "Women's Open")
    pg.click('#sheet form[data-form=comp-entry] button[type=submit]'); pg.wait_for_timeout(150)
    c.ok(W(f"M.findComp(W, '{wl}').entries.length") == 2 and W('W.competitions.length') == 2, 'two teams in one competition, which exists once')
    c.ok(W(f"M.findComp(W, '{wl}').entries.every(e => M.findSeason(M.findTeam(W, e.teamId), e.seasonId))"), 'each entry is a team’s season')
    pg.click('[data-act=comp-entry-new]'); pg.wait_for_selector('#sheet form[data-form=comp-entry]')
    pg.fill('#sheet input[name=division]', 'mixed open'); pg.click('#sheet form[data-form=comp-entry] button[type=submit]'); pg.wait_for_timeout(150)
    c.ok(pg.is_visible('#sheet [name=division][aria-invalid=true]') and W(f"M.findComp(W, '{wl}').entries.length") == 2, 'the same team, season and division can’t be entered twice')
    pg.keyboard.press('Escape')
    c.ok(W("M.teamEntries(W, 'team1', M.activeSeason(D).id).length") == 2, 'DragonTag is in two competitions this season')
    # a fixture in the league, in two days
    pg.goto(url + '#matches'); pg.wait_for_timeout(150)
    pg.click('[data-act=match-new]'); pg.wait_for_selector('#sheet form[data-form=match]')
    pg.fill('#sheet input[name=opponent]', 'Como Crocs'); pg.fill('#sheet input[name=date]', W('M.addDays(M.isoDay(new Date()), 2)')); pg.fill('#sheet input[name=start]', '10:00')
    entry = W(f"M.findComp(W, '{wl}').entries.find(e => e.teamId === 'team1').id")
    pg.select_option('#sheet select[name=entry]', entry)
    pg.uncheck('#sheet input[name=tournament]')
    pg.click('#sheet form[data-form=match] button[type=submit]'); pg.wait_for_timeout(200); pg.keyboard.press('Escape')
    m = W("JSON.stringify(D.matches.find(m => m.opponent === 'Como Crocs'))"); m = json.loads(m)
    c.ok(m['entryId'] == entry and m['compId'] == wl and m['seasonId'] == W('M.activeSeason(D).id'), 'the fixture belongs to the entry, competition and season')
    pg.goto(url + '#matches'); pg.wait_for_timeout(150)
    txt = pg.inner_text('#view')
    c.ok('Winter League 2027 (Mixed Open)' in txt and 'NSW State Cup' in txt, 'matches show their competition')
    c.ok('vs Hills Hornets' in txt, 'a match from before competitions is still there and usable')
    # a friendly
    pg.click('[data-act=match-new]'); pg.wait_for_selector('#sheet form[data-form=match]')
    pg.fill('#sheet input[name=opponent]', 'Social Sharks'); pg.select_option('#sheet select[name=entry]', 'friendly'); pg.uncheck('#sheet input[name=tournament]')
    pg.click('#sheet form[data-form=match] button[type=submit]'); pg.wait_for_timeout(200); pg.keyboard.press('Escape')
    c.ok(W("D.matches.find(m => m.opponent === 'Social Sharks').friendly") is True and W("M.matchKind(W, D.matches.find(m => m.opponent === 'Social Sharks')).kind") == 'friendly', 'a friendly is marked as one')
    # tournament day into the State Cup
    pg.click('[data-act=match-day-new]'); pg.wait_for_selector('#sheet form[data-form=match-day]')
    pg.fill('#sheet input[name=date]', '2027-03-21'); pg.fill('#sheet textarea[name=lines]', '8:30am, Wollongong Whales, 1, Quarter final')
    cupEntry = W(f"M.findComp(W, '{cup}').entries.find(e => e.teamId === 'team1').id")
    pg.select_option('#sheet select[name=entry]', cupEntry)
    pg.click('#sheet button[type=submit]'); pg.wait_for_timeout(200)
    c.ok(W("D.matches.find(m => m.opponent === 'Wollongong Whales').entryId") == cupEntry and 'Wollongong Whales' in pg.inner_text('#view'), 'tournament day: matches added to the State Cup and shown in the draw')
    # Home: the league fixture is labelled with its competition
    pg.goto(url + '#home'); pg.wait_for_timeout(200)
    c.ok(pg.locator('.tl-row', has_text='Como Crocs').count() == 1 and 'Winter League 2027' in pg.locator('.tl-row', has_text='Como Crocs').inner_text(), 'Home: the fixture with its competition')
    # rules and reports
    pg.goto(url + '#rules'); pg.wait_for_timeout(150)
    c.ok('Competition by-laws' in pg.inner_text('#view') and 'Games are 2 × 20 minutes.' in pg.inner_text('#view'), 'Rules: the competition’s by-laws, apart from the team’s')
    W(f"(D.matches.find(m => m.opponent === 'Como Crocs').status = 'played', D.matches.find(m => m.opponent === 'Como Crocs').result = {{ us: 7, them: 3 }}, 1)")
    pg.goto(url + '#reports'); pg.wait_for_timeout(150)
    txt = pg.inner_text('#view')
    c.ok('Competitions' in txt and 'Winter League 2027' in txt and 'W1 D0 L0' in txt and 'No ladder' in txt, 'Reports: our results per competition, no ladder')
    # unlinked matches in the dates are offered, never linked on their own
    W("(D.matches.push({ id: 'loose1', date: M.addDays(M.isoDay(new Date()), 5), opponent: 'Loose Lions', status: 'scheduled', rsvp: {}, result: {}, seasonId: M.activeSeason(D).id }), 1)")
    pg.evaluate(act, ['comp-open', {'id': wl}]); pg.wait_for_timeout(150)
    c.ok(W("D.matches.find(m => m.id === 'loose1').entryId") is None and 'not linked' in pg.inner_text('#view'), 'a match in the dates is offered, not linked')
    pg.click('[data-act=comp-link]'); pg.wait_for_selector('#sheet form[data-form=comp-link]')
    pg.check('#sheet input[name=m][value=loose1]'); pg.click('#sheet form[data-form=comp-link] button[type=submit]'); pg.wait_for_timeout(150)
    c.ok(W("D.matches.find(m => m.id === 'loose1').entryId") == entry, 'linked once the coach ticks it')
    # withdraw keeps fixtures; complete keeps results
    pg.click(f'[data-act=comp-withdraw][data-entry="{entry}"]'); pg.wait_for_timeout(150)
    c.ok(W(f"M.findComp(W, '{wl}').entries.find(e => e.id === '{entry}').status") == 'withdrawn' and W("D.matches.find(m => m.opponent === 'Como Crocs').entryId") == entry, 'withdrawing keeps the fixtures')
    pg.click(f'[data-act=comp-reenter][data-entry="{entry}"]'); pg.wait_for_timeout(100)
    pg.click('[data-act=comp-move][data-to=active]'); pg.wait_for_timeout(100); pg.click('[data-act=comp-move][data-to=completed]'); pg.wait_for_timeout(150)
    c.ok(W(f"M.findComp(W, '{wl}').status") == 'completed' and 'Won 7–3' in pg.inner_text('#view'), 'a completed competition keeps its results')
    # archive the other team: its entry stays
    pg.goto(url + '#teams'); pg.wait_for_timeout(100); pg.click(f'[data-act=team-archive][data-id="{women}"]'); pg.wait_for_timeout(150)
    pg.evaluate(act, ['comp-open', {'id': wl}]); pg.wait_for_timeout(150)
    c.ok('(archived team)' in pg.inner_text('#view') and W(f"M.findComp(W, '{wl}').entries.length") == 2, 'an archived team’s entry is kept')
    # Seasons sheet: this season's competitions, enter from there
    pg.evaluate(act, ['season-open', {}]); pg.wait_for_selector('#sheet [data-act=comp-enter]')
    c.ok('Winter League 2027' in pg.inner_text('#sheet') and 'NSW State Cup' in pg.inner_text('#sheet'), 'the season shows its competitions')
    pg.keyboard.press('Escape')
    # players: their own competitions only
    pg.evaluate(act, ['preview-on', {}]); pg.goto(url + '#matches'); pg.wait_for_timeout(200)
    txt = pg.inner_text('#view')
    c.ok('Playing in' in txt and 'Winter League 2027' in txt and "Women's Open" not in txt and 'Titans Women' not in txt, 'players see their team’s competitions, not other teams’ entries')
    pg.goto(url + '#rules'); pg.wait_for_timeout(150)
    c.ok('Games are 2 × 20 minutes.' in pg.inner_text('#view'), 'players see the competition by-laws')
    pg.evaluate(act, ['preview-off', {}]); pg.wait_for_timeout(100)
    for w in (390, 1280):
        pg.set_viewport_size({'width': w, 'height': 900}); pg.evaluate(act, ['comp-open', {'id': wl}]); pg.wait_for_timeout(150)
        c.ok(pg.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'[{w}] competition page: no sideways scroll')
    pg.screenshot(path=shot('competition.png'))
    ok = c.done(errs); b.close()
srv.shutdown(); sys.exit(0 if ok else 1)
