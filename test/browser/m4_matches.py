import sys; from harness import *
from playwright.sync_api import sync_playwright
build(); srv, url = serve()
c = Check()
act = "([a, ds]) => { const b = document.createElement('button'); b.dataset.act = a; Object.assign(b.dataset, ds || {}); document.body.appendChild(b); b.click(); b.remove(); }"
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx, pg, errs = page(b, url + '#home')
    pg.click('text=Load a sample squad'); pg.wait_for_timeout(300)
    d = lambda js: pg.evaluate(f'(() => {{ const D = window.__team.data, M = window.__team.M; return {js}; }})()')
    txt = pg.inner_text('#view')
    c.ok('Match day' in txt and 'Hills Hornets' in txt, 'Home shows the coming match day')
    c.ok('availability repl' in txt or 'No lineup' in txt, 'match day lists what’s still to sort')
    pg.evaluate(act, ['train-view', {'v': 'matches'}]); pg.wait_for_timeout(150)
    txt = pg.inner_text('#view')
    c.ok('Won 6–4' in txt and 'NSW State Cup' in txt and 'Coffs Coast' in txt, 'matches: result, tournament draw')
    c.ok('Won' in txt and 'Tries for–against' in txt, 'team record shown')
    # tournament day bulk add
    pg.evaluate(act, ['match-day-new', {}]); pg.fill('#sheet input[name=date]', '2027-03-21')
    pg.fill('#sheet textarea[name=lines]', '8:30am, Wollongong Whales, 1, Quarter final\n1.15pm, TBC, Field 6, Semi')
    pg.click('#sheet button[type=submit]'); pg.wait_for_timeout(150)
    ms = d("D.matches.filter(m => m.date === '2027-03-21').map(m => [m.start, m.opponent, m.field, m.round])")
    c.ok(ms == [['08:30', 'Wollongong Whales', '1', 'Quarter final'], ['13:15', 'TBC', '6', 'Semi']], f'draw lines parsed: {ms}')
    # open the upcoming trial: availability, lineup, readiness
    mid = d("D.matches.find(m => m.opponent === 'Hills Hornets').id")
    pg.evaluate(act, ['match-open', {'id': mid}]); pg.wait_for_selector('#sheet form[data-form=match-lineup]')
    c.ok('no reply' in pg.inner_text('#sheet'), 'availability counts in the match sheet')
    pg.click('#sheet form[data-form=match-lineup] button[type=submit]'); pg.wait_for_timeout(150)
    lu = d(f"D.matches.find(m => m.id === '{mid}').lineupId")
    c.ok(bool(lu) and d(f"D.lineups.find(l => l.id === '{lu}').name").startswith('vs Hills Hornets'), 'match lineup made from a saved lineup')
    c.ok(d(f"D.lineups[0].id !== '{lu}'"), 'saved lineup left alone')
    sheet = pg.inner_text('#sheet')
    c.ok('said they can’t play' in sheet or 'to fix' in sheet or 'Ready' in sheet, 'readiness checked against availability')
    # the copied lineup has a player who said no -> issue
    p3 = d("D.players.slice(0, 11)[3].id")
    d(f"(D.lineups.find(l => l.id === '{lu}').slots[0].playerId = '{p3}', 0)")
    chk = d(f"M.lineupCheck(D, D.lineups.find(l => l.id === '{lu}'), D.matches.find(m => m.id === '{mid}'))")
    c.ok(any('can’t play' in x for x in chk['issues']), 'a player who said no is flagged')
    pg.click('#sheet [data-act=match-lineup-open]'); pg.wait_for_timeout(150)
    c.ok('Match lineup: vs Hills Hornets' in pg.inner_text('#view'), 'Lineup page shows the match banner')
    # result
    pg.evaluate(act, ['match-open', {'id': mid}]); pg.wait_for_selector('#sheet form[data-form=match-result]')
    pg.check('#sheet input[name=status][value=played]'); pg.click('#sheet form[data-form=match-result] button[type=submit]'); pg.wait_for_timeout(100)
    c.ok(pg.locator('#sheet .err').count() == 1, 'scores required for a played match')
    pg.fill('#sheet input[name=us]', '3'); pg.fill('#sheet input[name=them]', '5'); pg.click('#sheet form[data-form=match-result] button[type=submit]'); pg.wait_for_timeout(150)
    c.ok(d(f"M.matchOutcome(D.matches.find(m => m.id === '{mid}'))") == 'loss', 'result saved as a loss')
    # move the match: its linked lift task follows
    lift = d(f"D.tasks.find(t => t.matchId === '{mid}' && t.kind === 'lift').id")
    pg.evaluate(act, ['match-edit', {'id': mid}]); pg.fill('#sheet input[name=start]', '11:00'); pg.fill('#sheet input[name=date]', d(f"M.addDays(D.matches.find(m => m.id === '{mid}').date, 1)"))
    pg.click('#sheet button[type=submit]'); pg.wait_for_selector('text=What should happen to them?')
    pg.click('text=Move them with it'); pg.wait_for_timeout(150)
    c.ok(d(f"D.tasks.find(t => t.id === '{lift}').date") == d(f"D.matches.find(m => m.id === '{mid}').date"), 'linked tasks moved with the match')
    # cancel the match -> cancel its tasks
    pg.evaluate(act, ['match-edit', {'id': mid}]); pg.select_option('#sheet select[name=status]', 'cancelled'); pg.click('#sheet button[type=submit]')
    pg.wait_for_selector('text=Cancel them too'); pg.click('text=Cancel them too'); pg.wait_for_timeout(150)
    c.ok(d(f"D.matches.find(m => m.id === '{mid}').status") == 'cancelled' and d(f"D.tasks.find(t => t.id === '{lift}').cancelled"), 'match and its tasks cancelled')
    # WhatsApp texts
    pg.goto(url + '#messages'); pg.wait_for_timeout(100)
    pg.evaluate(act, ['tpl', {'t': 'results'}]); pg.wait_for_timeout(100)
    c.ok('Northern Beaches: Won 6–4' in pg.input_value('#msg'), 'results message')
    pg.evaluate(act, ['tpl', {'t': 'match'}]); pg.wait_for_timeout(100)
    c.ok('Coffs Coast' in pg.input_value('#msg') or 'vs' in pg.input_value('#msg'), 'next match message')
    # players: no coach notes, no availability, scores visible
    pg.evaluate(act, ['preview-on', {}]); pg.goto(url + '#matches'); pg.wait_for_timeout(150)
    txt = pg.inner_text('#view')
    c.ok('Won 6–4' in txt and 'Kick chase too slow' not in txt and 'available' not in txt.lower().replace('unavailable', ''), 'players see scores, not notes or availability')
    pg.screenshot(path=shot('m4-player.png'), full_page=True)
    ok = c.done(errs); b.close()
srv.shutdown(); sys.exit(0 if ok else 1)
