import sys; from harness import *
from playwright.sync_api import sync_playwright
build(); srv, url = serve()
c = Check()
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx, pg, errs = page(b, url + '#home')
    pg.wait_for_selector('text=Load a sample squad'); pg.click('text=Load a sample squad')
    pg.wait_for_timeout(300)
    d = lambda js: pg.evaluate(f'(() => {{ const D = window.__team.data; return {js}; }})()')
    c.ok(d('D.players.length') == 16, 'sample loaded')
    # M0.3 BBQ: 1 accepted, 1 invited, 1 declined, need 3 -> 1 of 3 confirmed
    pg.goto(url + '#tasks'); pg.wait_for_timeout(200)
    txt = pg.inner_text('#view')
    c.ok('Spots confirmed' in txt and 'Invited, no reply' in txt, 'task dashboard shown')
    c.ok('1 of 3 confirmed · 1 awaiting reply · 1 open' in txt, 'BBQ coverage split: ' + str([l for l in txt.split('\n') if 'confirmed' in l][:3]))
    # M0.2 move a session with a linked gear-bag task
    sid, tid = d("(() => { const s = D.sessions.find(s => s.date >= new Date().toISOString().slice(0,10)); const t = D.tasks.find(t => t.sessionId === s.id); return [s.id, t.id]; })()")
    pg.evaluate("id => { const b = document.createElement('button'); b.dataset.act = 'edit-session'; b.dataset.id = id; document.body.appendChild(b); b.click(); b.remove(); }", sid)
    pg.fill('#sheet input[name=start]', '17:30'); pg.click('#sheet button[type=submit]')
    c.ok(pg.is_visible('text=What should happen to it?'), 'linked task choice offered')
    pg.click('text=Move them with it'); pg.wait_for_timeout(200)
    c.ok(d(f"D.tasks.find(t => t.id === '{tid}').start") == '17:30', 'task moved with the session')
    # cancel with tasks -> cancel too, then reinstate
    pg.evaluate("id => { const b = document.createElement('button'); b.dataset.act = 'cancel-session'; b.dataset.id = id; document.body.appendChild(b); b.click(); b.remove(); }", sid)
    pg.click('text=Cancel them too'); pg.wait_for_timeout(200)
    c.ok(d(f"D.tasks.find(t => t.id === '{tid}').cancelled") is True, 'task cancelled with session')
    pg.evaluate("id => { const b = document.createElement('button'); b.dataset.act = 'cancel-session'; b.dataset.id = id; document.body.appendChild(b); b.click(); b.remove(); }", sid)
    pg.wait_for_timeout(200)
    c.ok(d(f"D.tasks.find(t => t.id === '{tid}').cancelled") is False, 'task reinstated with session')
    # M0.4 WhatsApp: open a task message -> prepared, ask bar -> sent
    pg.goto(url + '#tasks'); pg.wait_for_timeout(150)
    pg.click('.task:has-text("Run the BBQ") >> nth=0')
    pg.wait_for_selector('#sheet .tp-row')
    pg.context.on('page', lambda np: np.close())
    pg.click('#sheet [data-act="task-share"]'); pg.wait_for_timeout(1500)
    c.ok(pg.is_visible('#ask') and 'Did you send it?' in pg.inner_text('#ask'), 'asked whether it was sent')
    c.ok(d("D.messages[0].status") == 'prepared', 'logged as prepared')
    pg.click('#ask [data-act="msg-sent"]'); pg.wait_for_timeout(100)
    c.ok(d("D.messages[0].status") == 'sent', 'marked as sent')
    # M2.3 car full: select options disabled
    pg.keyboard.press('Escape'); pg.goto(url + '#tasks'); pg.wait_for_timeout(150)
    pg.click('.task:has-text("Lifts to the Hills game") >> nth=0'); pg.wait_for_selector('#sheet .tp-car')
    c.ok('without a seat' in pg.inner_text('#sheet'), 'lift shows riders without a seat')
    pg.keyboard.press('Escape')
    # M0.1 reset: clear squad only
    pg.evaluate("() => { const b = document.createElement('button'); b.dataset.act = 'start-over'; document.body.appendChild(b); b.click(); b.remove(); }")
    pg.check('#sheet input[value=squad]'); pg.click('#sheet button[type=submit]'); pg.wait_for_timeout(200)
    c.ok(d('D.players.length') == 0 and d('D.helpers.length') == 5, 'squad cleared, helpers kept')
    c.ok(d("D.tasks.every(t => t.people.every(p => p.who.startsWith('h:')))"), 'no task points at a removed player')
    c.ok(d("D.sessions.every(s => !Object.keys(s.attendance).length)"), 'roll calls cleared with the squad')
    pg.screenshot(path=shot('m0.png'))
    ok = c.done(errs)
    b.close()
srv.shutdown()
sys.exit(0 if ok else 1)
