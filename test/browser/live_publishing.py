import sys, json, base64; from harness import *; from ghmock import GitHubMock
from playwright.sync_api import sync_playwright
build(); srv, url = serve(); gh = GitHubMock()
c = Check(); errs = []
act = "([a, ds]) => { const b = document.createElement('button'); b.dataset.act = a; Object.assign(b.dataset, ds || {}); document.body.appendChild(b); b.click(); b.remove(); }"
GH = json.dumps({'owner': 'o', 'repo': 'r', 'token': 'tok', 'autoPublish': False})
def device(b, width=390, github=True):
    ctx = b.new_context(viewport={'width': width, 'height': 860})
    if github: ctx.add_init_script(f"if (!localStorage.getItem('tm-github')) localStorage.setItem('tm-github', {json.dumps(GH)});")
    ctx.route('https://api.github.com/**', gh.handle)
    ctx.route('**/fonts.g*/**', lambda r: r.abort()); ctx.route('https://wa.me/**', lambda r: r.fulfill(body='wa'))
    pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('dialog', lambda d: d.accept())
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'Failed to load resource' not in m.text else None)
    return ctx, pg
def W(pg, js): return pg.evaluate(f'(() => {{ const W = window.__team.ws, D = window.__team.data, M = window.__team.M, S = window.__team.S; return {js}; }})()')
def wait_pub(pg, t=20000): pg.wait_for_function("!window.__team.S.publishing && window.__team.S.pub !== 'busy'", timeout=t); pg.wait_for_timeout(100)
b64u = lambda s: base64.urlsafe_b64encode(s.encode()).decode().rstrip('=')
with sync_playwright() as p:
    b = p.chromium.launch()
    # Device 1: test mode, sample, a second team, then go live
    ctx1, d1 = device(b); d1.goto(url + '#home'); d1.click('text=Load a sample squad'); d1.wait_for_timeout(200)
    d1.evaluate(act, ['teams', {}]); d1.click('text=New team'); d1.fill('#sheet input[name=name]', 'Under 16s'); d1.click('#sheet button[type=submit]'); d1.wait_for_timeout(150)
    d1.evaluate(act, ['add-player', {}]); d1.fill('#sheet input[name=name]', 'Ava Young'); d1.click('#sheet button[value=save]'); d1.wait_for_timeout(100)
    u16 = W(d1, 'D.id')
    d1.evaluate(act, ['go-live', {}]); d1.fill('#sheet input[name=coach]', 'coach password one'); d1.fill('#sheet input[name=coach2]', 'coach password one')
    d1.fill('#sheet input[name=team]', 'team password one'); d1.fill('#sheet input[name=team2]', 'team password one'); d1.click('#sheet button[type=submit]')
    d1.wait_for_function('window.__team.S.trial === false', timeout=20000); wait_pub(d1, 40000)
    files = gh.files()
    c.ok(sorted(files) == sorted(['coach.enc.json', 'team.enc.json', f'team-{u16}.enc.json']), f'one players’ file per team: {sorted(files)}')
    c.ok(all('Mia Tuala' not in v and 'Ava Young' not in v and set(json.loads(v)) <= {'format','version','role','kdf','salt','iv','data'} for v in files.values()), 'nothing readable in the published files')
    c.ok(W(d1, 'S.pub') == 'ok' and gh.dispatches == 1, 'published and site rebuild started')
    c.ok(d1.evaluate("localStorage.getItem('tm-test-data')") is None, 'unencrypted test copy removed')
    u16pass = W(d1, f"M.findTeam(W, '{u16}').teamPass")
    c.ok(len(u16pass) >= 15 and u16pass != 'team password one', 'second team got its own password')
    # Players: the U16 invite link opens only U16; the first team's password opens only the first team
    ctx2, pl = device(b, github=False); pl.goto(url + f'#join={b64u(u16pass)}.{u16}'); pl.wait_for_function('window.__team.teamData', timeout=20000)
    names = pl.evaluate("window.__team.teamData.players.map(p => p.name)")
    c.ok(names == ['Ava Young'], f'U16 link opens U16 only: {names}')
    c.ok('Mia' not in json.dumps(pl.evaluate("window.__team.teamData")), 'no other team’s data on a U16 phone')
    ctx3, pl2 = device(b, github=False); pl2.goto(url + '#home'); pl2.wait_for_selector('input[name=password]')
    pl2.fill('input[name=password]', u16pass); pl2.click('button[type=submit]'); pl2.wait_for_function('window.__team.teamData', timeout=30000)
    c.ok(pl2.evaluate("window.__team.teamData.team.name") == 'Under 16s', 'typed U16 password finds the U16 file')
    pl2.evaluate(act, ['sign-out', {}]); pl2.wait_for_selector('input[name=password]')
    pl2.fill('input[name=password]', 'team password one'); pl2.click('button[type=submit]'); pl2.wait_for_function('window.__team.teamData', timeout=30000)
    c.ok(pl2.evaluate("window.__team.teamData.team.name") == 'DragonTag Mixed 20s' and pl2.evaluate("window.__team.teamData.players.length") == 16, 'first team password opens the first team')
    c.ok(pl2.evaluate("JSON.stringify(window.__team.teamData).includes('Rachel')") is False, 'no helper names in the players’ copy')
    # Device 2: the coach on a laptop signs in from GitHub
    ctx4, d2 = device(b, 1280); d2.goto(url + '#home'); d2.wait_for_selector('text=I\'m the coach'); d2.click('text=I\'m the coach')
    d2.fill('input[name=password]', 'coach password one'); d2.click('button[type=submit]'); d2.wait_for_function('window.__team.ws', timeout=30000)
    c.ok(W(d2, 'M.teamsOf(W).length') == 2, 'second device has both teams')
    # Both edit, device 2 publishes first
    W(d2, "(window.__team.data.notices.unshift({ id: 'n-d2', at: new Date().toISOString(), text: 'Notice from the laptop' }), 0)")
    d2.evaluate("() => { window.__team.data.updatedAt = 'x'; }")
    d2.evaluate(act, ['publish', {}]); 
    # save() isn't exposed, so publish after marking dirty through a real edit instead
    d2.evaluate(act, ['add-notice', {}]); d2.fill('#sheet textarea[name=text]', 'Second laptop notice'); d2.click('#sheet button[type=submit]'); d2.wait_for_timeout(100)
    d2.evaluate(act, ['publish', {}]); wait_pub(d2)
    c.ok(W(d2, 'S.pub') == 'ok', 'laptop published')
    d1.evaluate(act, ['edit-player', {'id': W(d1, "W.players.find(p => p.name.startsWith('Mia')).id")}]) if W(d1, 'D.id') == 'team1' else None
    if W(d1, 'D.id') != 'team1':
        d1.click('.team-btn'); d1.click('#sheet [data-act=team-pick][data-id=team1]'); d1.wait_for_timeout(100)
        d1.evaluate(act, ['edit-player', {'id': W(d1, "W.players.find(p => p.name.startsWith('Mia')).id")}])
    d1.fill('#sheet input[name=number]', '99'); d1.click('#sheet button[value=save]'); d1.wait_for_timeout(100)
    d1.evaluate(act, ['publish', {}]); wait_pub(d1)
    c.ok(W(d1, 'S.pub') == 'conflict', 'phone sees the clash')
    d1.evaluate(act, ['conflict', {}]); d1.wait_for_selector('#sheet form[data-form=merge]', timeout=20000)
    txt = d1.inner_text('#sheet')
    c.ok('Changed on this phone only (1)' in txt and 'Player: Mia Tuala' in txt, 'shows this phone’s change')
    c.ok('Changed on the other device only' in txt and 'Second laptop notice' in txt, 'shows the other device’s change')
    d1.click('#sheet form[data-form=merge] button[type=submit]'); wait_pub(d1)
    c.ok(W(d1, 'S.pub') == 'ok', 'combined copy published')
    d2.evaluate(act, ['load-latest', {}]); d2.wait_for_timeout(1500)
    c.ok(W(d2, "W.players.find(p => p.name.startsWith('Mia')).number") == '99' and W(d2, "W.notices.some(n => n.text === 'Second laptop notice')"), 'both changes kept')
    # Failure recovery: GitHub errors once, then a retry works
    d1.evaluate(act, ['add-notice', {}]); d1.fill('#sheet textarea[name=text]', 'After an outage'); d1.click('#sheet button[type=submit]'); d1.wait_for_timeout(100)
    gh.fail_next = [500]; d1.evaluate(act, ['publish', {}]); wait_pub(d1)
    c.ok(W(d1, 'S.pub') == 'error' and 'Try again' in d1.inner_text('#status'), 'error shown with Try again')
    c.ok(W(d1, 'S.dirty') is True, 'changes still kept on the phone')
    d1.click('#status button'); wait_pub(d1)
    c.ok(W(d1, 'S.pub') == 'ok' and 'After an outage' not in json.dumps(gh.files()), 'retry published (still encrypted)')
    # Offline: the coach is told changes wait; a player sees the saved copy
    ctx1.set_offline(True); d1.wait_for_timeout(200)
    d1.evaluate(act, ['add-notice', {}]); d1.fill('#sheet textarea[name=text]', 'Written offline'); d1.click('#sheet button[type=submit]'); d1.wait_for_timeout(200)
    c.ok('Offline' in d1.inner_text('#status') and 'will publish' in d1.inner_text('#status'), 'coach told changes will publish when back online')
    ctx1.set_offline(False); d1.wait_for_timeout(300)
    c.ok('Offline' not in d1.inner_text('#status'), 'status clears when back online')
    d1.evaluate(act, ['publish', {}]); wait_pub(d1)
    ctx3.set_offline(True); pl2.evaluate(act, ['refresh', {}]); pl2.wait_for_timeout(800)
    c.ok('copy saved on this phone' in pl2.inner_text('#toast') and not pl2.is_hidden('#status'), 'player offline: shown the saved copy')
    ctx3.set_offline(False)
    # Archive U16: its players' file comes off the site; restoring brings it back
    d1.evaluate(act, ['teams', {}]); d1.click(f'[data-act=team-archive][data-id="{u16}"]'); d1.wait_for_timeout(100)
    d1.evaluate(act, ['publish', {}]); wait_pub(d1)
    c.ok(f'team-{u16}.enc.json' not in gh.files() and 'team.enc.json' in gh.files(), 'archived team’s file removed')
    pl.evaluate(act, ['refresh', {}]); pl.wait_for_timeout(1500)
    c.ok('Up to date' not in pl.inner_text('#toast'), 'archived team’s players can’t refresh it')
    d1.evaluate(act, ['teams', {}]); d1.click(f'[data-act=team-restore][data-id="{u16}"]'); d1.wait_for_timeout(100)
    d1.evaluate(act, ['publish', {}]); wait_pub(d1)
    c.ok(f'team-{u16}.enc.json' in gh.files(), 'restored team’s file is back')
    # Encrypted backup export/import round trip (coach password)
    with d1.expect_download() as dl: d1.evaluate(act, ['export', {}])
    path = dl.value.path(); bk = json.load(open(path))
    c.ok(bk.get('format') == 'team-manager' and 'Mia Tuala' not in open(path).read(), 'backup is encrypted')
    d1.evaluate(act, ['start-over', {}]); d1.click('#sheet [data-p=all]'); d1.click('#sheet button[type=submit]'); d1.wait_for_timeout(200)
    c.ok(W(d1, 'D.players.length') == 0, 'team cleared')
    d1.evaluate("() => { window.__team.state.importKind = 'backup'; }")
    d1.set_input_files('#import-file', path); d1.wait_for_selector('#sheet [data-act=import-do]')
    d1.click('#sheet [data-act=import-do][data-m=all]'); d1.wait_for_timeout(300)
    c.ok(W(d1, "W.players.length") == 16 and W(d1, 'M.teamsOf(W).length') == 2, 'encrypted backup restored every team')
    c.ok(W(d1, 'W.teamPass') == 'team password one', 'team passwords kept on restore')
    # Rules: the coach can start the rule book check from the Rules page
    d1.evaluate(act, ['tab', {'tab': 'rules'}]); d1.wait_for_selector('[data-act=rules-check]')
    d1.click('[data-act=rules-check]'); d1.wait_for_timeout(500)
    c.ok(gh.workflows[-1:] == ['rules-watch.yml'] and 'Checking the rule books' in d1.inner_text('#toast'), 'Check the rule books now starts the Rules watch')
    ok = c.done(errs); b.close()
srv.shutdown(); sys.exit(0 if ok else 1)
