import sys; from harness import *
from playwright.sync_api import sync_playwright
build(); srv, url = serve()
c = Check()
act = "([a, ds]) => { const b = document.createElement('button'); b.dataset.act = a; Object.assign(b.dataset, ds || {}); document.body.appendChild(b); b.click(); b.remove(); }"
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx, pg, errs = page(b, url + '#home')
    ctx.on('page', lambda np: np.close())
    pg.wait_for_selector('text=Load a sample squad'); pg.click('text=Load a sample squad'); pg.wait_for_timeout(300)
    d = lambda js: pg.evaluate(f'(() => {{ const D = window.__team.data; return {js}; }})()')
    pg.goto(url + '#agenda'); pg.wait_for_timeout(200)
    txt = pg.inner_text('#view')
    c.ok('Next six weeks' in txt and 'TRAINING' in txt.upper() and 'HELP NEEDED' in txt.upper(), 'agenda lists training and tasks')
    c.ok('attending' in txt and 'no reply' in txt, 'agenda shows RSVP counts to the coach')
    sid = d("D.sessions.find(s => s.date >= new Date().toISOString().slice(0,10)).id")
    pg.evaluate(act, ['rsvp-open', {'k': 'session', 'id': sid}])
    pg.wait_for_selector('#rsvp-sum')
    before = d(f"Object.keys(D.sessions.find(s => s.id === '{sid}').rsvp).length")
    row = pg.locator('#sheet .roll-row').nth(0)
    row.locator('[data-v=no]').click(); row.locator('[data-v=no]').click()
    after = d(f"Object.keys(D.sessions.find(s => s.id === '{sid}').rsvp).length")
    c.ok(after == before - 1 or after == before, f'tap again clears a reply ({before}->{after})')
    pid = d("D.players.slice().sort((a,b)=>(a.status==='available'?0:1)-(b.status==='available'?0:1)||a.name.localeCompare(b.name))[0].id")
    row.locator('[data-v=yes]').click()
    c.ok(d(f"window.__team.data.sessions.find(s => s.id === '{sid}').rsvp['{pid}'].v") == 'yes', 'RSVP recorded with who recorded it')
    c.ok(d(f"Object.keys(D.sessions.find(s => s.id === '{sid}').attendance).length") == 0, 'RSVP does not touch attendance')
    pg.click('#sheet [data-act="rsvp-ask"]'); pg.wait_for_timeout(200)
    c.ok('Availability' in pg.input_value('#msg') and 'YES' in pg.input_value('#msg'), 'availability template filled in')
    pg.evaluate(act, ['roll', {'id': sid}]); pg.wait_for_timeout(100)
    c.ok('Said: attending' in pg.inner_text('#sheet'), 'roll call shows what they said')
    pg.keyboard.press('Escape')
    # player preview: reply buttons, no RSVP counts, no names on tasks
    pg.evaluate(act, ['preview-on', {}]); pg.goto(url + '#agenda'); pg.wait_for_timeout(200)
    txt = pg.inner_text('#view')
    c.ok('Coming' in txt and 'Not sure' in txt, 'players get reply buttons')
    c.ok('attending' not in txt and 'no reply' not in txt, 'players never see RSVP counts')
    c.ok('Rachel' not in txt, 'no helper names for players')
    n_msgs = d('D.messages.length')
    pg.locator('[data-act=reply][data-v=yes]').first.click(); pg.wait_for_timeout(200)
    c.ok(d('D.messages.length') == n_msgs, 'a player reply records nothing')
    c.ok('the coach records it' in pg.inner_text('#toast'), 'player told the coach records it')
    pg.screenshot(path=shot('m2-player.png'), full_page=True)
    ok = c.done(errs)
    b.close()
srv.shutdown()
sys.exit(0 if ok else 1)
